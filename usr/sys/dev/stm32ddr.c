void
ddrinit()
{
	unsigned int *r;
	int i;

	RCC(0x420) = 0x100;
	while ((RCC(0x428) & 0x100) == 0)
		;
	RCC(0x4D0) &= ~1;
	while (RCC(0x4D0) & 2)
		;
	RCC(0x480) = (RCC(0x480) & ~7) | 1;
	RCC(0x4D4) = 0x00020041;
	RCC(0x4D8) = 0x00000101;
	RCC(0x4DC) = 0x1400 << 3;
	RCC(0x4DC) |= 0x10000;
	RCC(0x4D0) |= 0x70;
	RCC(0x4D0) |= 1;
	while ((RCC(0x4D0) & 2) == 0)
		;

	if (R(0x5000100C) & 0x1000) {
		R(0x5000100C) |= 0x800;
		R(0x5000100C) &= ~0x1000;
	}
	RCC(0x780) = 2;
	RCC(0x740) = 0x800;
	(void)RCC(0x740);
	R(0x5C006008) = 0;
	R(0x5C006114) = 0xFFFFFFFF;
	R(0x5C006110) = 0xC0000001;
	R(0x5C006008) = 1;

	DDRITFCR &= ~0x100;
	DDRITFCR |= 0xFC000;
	DDRITFCR |= 0x251;
	DDRITFCR &= ~0xC0000;
	DDRITFCR &= ~0x4000;
	for (i = 0; i < 10000; i++)
		(void)DDRITFCR;
	DDRC(0x1B0) &= ~1;
	for (r = ddrc; *r != 0xFFFF; r += 2)
		DDRC(r[0]) = r[1];
	DDRITFCR &= ~0x38000;
	for (r = dphy; *r != 0xFFFF; r += 2)
		DPHY(r[0]) = r[1];
	while ((DPHY(0x00C) & 1) == 0)
		;

	DPHY(0x004) = 0x1007F;
	for (i = 0; i < 10000; i++)
		(void)DDRITFCR;
	while ((DPHY(0x00C) & 0x3E1) == 0)
		;
	DDRC(0x320) &= ~1;
	DDRC(0x1B0) |= 1;
	DDRC(0x320) |= 1;
	while ((DDRC(0x324) & 1) == 0)
		;
	while ((DDRC(0x004) & 7) != 1)
		;

	DDRC(0x320) &= ~1;
	DDRC(0x1B0) &= ~1;
	DDRC(0x060) |= 1;
	DDRC(0x320) |= 1;
	while ((DDRC(0x324) & 1) == 0)
		;
	DPHY(0x004) = 0x81;
	for (i = 0; i < 10000; i++)
		(void)DDRITFCR;
	while ((DPHY(0x00C) & 0x3E1) == 0)
		;
	DDRC(0x320) &= ~1;
	DDRC(0x060) = 0;
	DDRC(0x1B0) |= 1;
	DDRC(0x320) |= 1;
	while ((DDRC(0x324) & 1) == 0)
		;

	DDRC(0x490) |= 1;
	DDRITFCR |= 0x100;
}
